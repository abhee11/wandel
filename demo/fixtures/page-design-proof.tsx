import {createRoot} from 'react-dom/client';
import {App} from '../../extension/sidepanel/App';
import {Session} from '../../extension/content/session';
import {Repository,BrowserStorage} from '../../extension/storage/store';
import {RecordSchema} from '../../extension/shared/model';
import type {Bridge} from '../../extension/sidepanel/bridge';
import '../../extension/sidepanel/style.css';
const query=new URL(location.href).searchParams,key=query.get('case')||'navigation';
if(!['theme','navigation','new-header','page-layout'].includes(key))throw new Error('Unknown acceptance case');
const evidence=await fetch('/docs/acceptance/verified-request-'+key+'.json').then(r=>r.json());
const stage=query.has('stage')?Number(query.get('stage')):evidence.stages.length-1;
const record=RecordSchema.parse({...evidence.record,draft:evidence.stages[stage].workflow||evidence.record.draft});
const root=new DOMParser().parseFromString(evidence.fixture,'text/html').body.firstElementChild as HTMLElement;
document.getElementById('proof-scene')!.replaceChildren(root);
const session=new Session(root,new Repository(new BrowserStorage()),new URL(record.draft.origin+record.draft.route),{assistantEnabled:true,directSelection:true});
await session.init();await session.dispatch({type:'loadRecord',record});await session.dispatch({type:'edit'});
const turns=evidence.stages.slice(0,stage+1).flatMap((s:{instruction:string;grounded:{message:string}})=>[{role:'user',text:s.instruction,status:'sent'},{role:'assistant',text:s.grounded.message}]);
sessionStorage.setItem('wandel:conversation:'+record.draft.id,JSON.stringify(turns));
const bridge:Bridge={send:command=>session.dispatch(command),subscribe:listener=>session.subscribe(listener)};
createRoot(document.getElementById('wandel-panel')!).render(<App bridge={bridge} demo/>);
window.addEventListener('pagehide',()=>session.destroy(),{once:true});
